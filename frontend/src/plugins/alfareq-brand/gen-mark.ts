/**
 * Writes `mark.generated.ts` from `assets/alfareq-mark.svg`.
 *
 * The console hands its built-in mark around as a data URI (the brand link, and
 * `next/og` for the favicon and the OpenGraph card), so the SVG is inlined once
 * here rather than fetched. Run after changing the artwork:
 *
 *   bun run src/plugins/alfareq-brand/gen-mark.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function markModule(svg: string): string {
  const uri = `data:image/svg+xml,${encodeURIComponent(svg.trim())}`;
  const version = createHash("sha256").update(svg.trim()).digest("hex").slice(0, 8);
  return [
    "// Generated by src/plugins/alfareq-brand/gen-mark.ts - do not edit.",
    "",
    "/** The Alfareeq mark: two linked capsules on a dark tile, as a data URI. */",
    `export const MARK_DATA_URI =\n  ${JSON.stringify(uri)};`,
    "",
    "/** Changes with the mark, so a browser holding the old favicon asks again. */",
    `export const MARK_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const svg = readFileSync(resolve(here, "assets/alfareq-mark.svg"), "utf8");
  writeFileSync(resolve(here, "mark.generated.ts"), markModule(svg));
}
