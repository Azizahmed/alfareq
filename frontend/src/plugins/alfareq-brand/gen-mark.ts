/**
 * Writes `mark.generated.ts` from `assets/alfareq-mark.svg` and
 * `assets/alfareq-wordmark.svg`, both traced from the logo as it was supplied.
 *
 * The console hands its built-in mark around as a data URI (the brand link, and
 * `next/og` for the favicon and the OpenGraph card), so the SVG is inlined once
 * here rather than fetched. Run after changing the artwork:
 *
 *   bun run src/plugins/alfareq-brand/gen-mark.ts
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function markModule(svg: string, wordmark: string): string {
  const uri = (text: string) => `data:image/svg+xml,${encodeURIComponent(text.trim())}`;
  const version = createHash("sha256").update(svg.trim()).digest("hex").slice(0, 8);
  const box = wordmark.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/);
  if (!box) throw new Error("The logo SVG needs a viewBox starting at 0 0");
  const aspect = Number((Number(box[1]) / Number(box[2])).toFixed(4));
  return [
    "// Generated by src/plugins/alfareq-brand/gen-mark.ts - do not edit.",
    "",
    "/** The Alfareeq mark: the logo's icon on a dark tile, as a data URI. */",
    `export const MARK_DATA_URI =\n  ${JSON.stringify(uri(svg))};`,
    "",
    "/** Changes with the mark, so a browser holding the old favicon asks again. */",
    `export const MARK_VERSION = ${JSON.stringify(version)};`,
    "",
    "/** The whole logo, the name in its own letters, as a one-colour data URI. */",
    `export const WORDMARK_DATA_URI =\n  ${JSON.stringify(uri(wordmark))};`,
    "",
    "/** The logo's width over its height. */",
    `export const WORDMARK_ASPECT_RATIO = ${aspect};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const read = (name: string) => readFileSync(resolve(here, "assets", name), "utf8");
  writeFileSync(
    resolve(here, "mark.generated.ts"),
    markModule(read("alfareq-mark.svg"), read("alfareq-wordmark.svg")),
  );
}
